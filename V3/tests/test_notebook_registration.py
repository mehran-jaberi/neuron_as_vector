"""Regression guard: the notebook registers its run before any plotting cell.

Defect (found 2026-10-25): ``register_run`` lived only in the **last** cell of
``V3/V3_SHD_experiment.ipynb`` (builder section "16. Register run"), after the training
plots, the checkpoint inspection, the test plots, the scalar-baseline training and the
comparison table.  A crash in any of those cells -- or a dead kernel, as happened to the
committed run ``2026-10-02_14-31-15`` -- lost the registry row of an otherwise complete
~2 h run, even though training and the official test had already finished.

The notebook is generated by ``V3/tools/build_notebook.py``; these tests read the built
artifact (the ipynb JSON) and never execute it.
"""

from __future__ import annotations

import json
from pathlib import Path

V3_ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = V3_ROOT / "V3_SHD_experiment.ipynb"

TRAINING_CALL = "train_variant(cfg"
REGISTRATION_CALL = "run_dir = register_run("
# cells that present or analyse results instead of producing them
PLOTTING_MARKERS = ("display(Image(", "import pandas as pd", "pd.DataFrame(", "save_json(")


def _code_cells() -> list[str]:
    nb = json.loads(NOTEBOOK.read_text(encoding="utf-8"))
    return ["".join(cell["source"]) for cell in nb["cells"] if cell["cell_type"] == "code"]


def _only(hits: list[int], what: str) -> int:
    assert len(hits) == 1, f"expected exactly one {what} cell, found cells {hits}"
    return hits[0]


def test_notebook_contains_exactly_one_register_run_call():
    """One configuration -> one registry row: no duplicate registration."""
    cells = _code_cells()
    index = _only([i for i, src in enumerate(cells) if REGISTRATION_CALL in src], "register_run")
    assert "registry, cfg," in cells[index], "the call must go through v3.registry.register_run"


def test_registration_is_the_next_code_cell_after_training():
    """Registration must not sit behind plotting, checkpoint or scalar-baseline cells."""
    cells = _code_cells()
    training = _only([i for i, src in enumerate(cells) if TRAINING_CALL in src], "training")
    registration = _only([i for i, src in enumerate(cells) if REGISTRATION_CALL in src], "registration")
    assert registration == training + 1, (
        "registration must immediately follow the training cell "
        f"(training at {training}, registration at {registration})"
    )


def test_registration_precedes_every_plotting_or_analysis_cell():
    cells = _code_cells()
    registration = _only([i for i, src in enumerate(cells) if REGISTRATION_CALL in src], "registration")
    plotting = [i for i, src in enumerate(cells) if any(m in src for m in PLOTTING_MARKERS)]
    assert plotting, "expected at least one plotting/analysis cell in the notebook"
    assert registration < min(plotting), (
        f"registration (cell {registration}) must come before the first plotting/analysis "
        f"cell (cell {min(plotting)}), otherwise a later crash loses the registry row"
    )


def test_registration_cell_carries_the_official_test_metrics():
    """The row written early must still hold the primary number (correct/total)."""
    cells = _code_cells()
    source = cells[_only([i for i, src in enumerate(cells) if REGISTRATION_CALL in src], "registration")]
    assert "test_variant(" in source, "the official test pass must run before the row is written"
    assert "test_metrics=test" in source, "the registry row must carry the test metrics"
    assert "history=variant.history_rows()" in source, "the row must carry the per-epoch history"
